svg = f'''<svg xmlns="http://www.w3.org/2000/svg">'''

for polygon in input_data:

    # --- Extract points ---
    points = []
    seen = set()

    for line in polygon.strip().splitlines():
        match = re.search(r"\[([-\d.]+),([-\d.]+)\]", line)
        if match:
            x = float(match.group(1))
            y = -float(match.group(2))  # flip Y for SVG

            key = (round(x, 6), round(y, 6))
            if key not in seen:
                seen.add(key)
                points.append((x, y))

    if not xs:
        # --- Bounds ---
        xs = [p[0] for p in points]
        ys = [p[1] for p in points]

        min_x, max_x = min(xs), max(xs)
        min_y, max_y = min(ys), max(ys)

        width = max_x - min_x
        height = max_y - min_y

    # --- SVG ---
    svg_points = [
        f"{x - min_x},{height - (y - min_y) + 25}"
        for x, y in points
    ]

    svg += (f'''
    <polygon
        points="{' '.join(svg_points)}"
        fill="white"
        stroke="black"
        stroke-width="0.5"/>''')

svg+= ('''
</svg>
''')

with open("building_outline.svg", "w") as f:
    f.write(svg)

